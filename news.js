function createNewsCard(story) {
  const card = document.createElement('article');
  card.className = 'news-post-card';

  const imageLink = document.createElement('a');
  imageLink.className = 'news-post-image-link';
  imageLink.href = `news/${story.id}.html`;
  imageLink.setAttribute('aria-label', `Open ${story.title}`);
  const image = document.createElement('img');
  image.className = 'news-post-image';
  image.src = story.image;
  image.alt = story.title;
  image.loading = 'lazy';
  image.decoding = 'async';
  imageLink.append(image);

  const content = document.createElement('div');
  content.className = 'news-post-content';
  const label = document.createElement('span');
  label.className = 'news-post-category';
  label.textContent = story.category;
  const title = document.createElement('h3');
  const titleLink = document.createElement('a');
  titleLink.href = `news/${story.id}.html`;
  titleLink.textContent = story.title;
  title.append(titleLink);
  const summary = document.createElement('p');
  summary.textContent = story.summary;
  const meta = document.createElement('div');
  meta.className = 'news-post-meta';
  const date = document.createElement('time');
  date.dateTime = story.date;
  date.textContent = new Date(`${story.date}T12:00:00`).toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric'
  });
  const byline = document.createElement('span');
  byline.textContent = `By ${story.author}`;
  meta.append(date, byline);
  const link = document.createElement('a');
  link.className = 'news-post-read';
  link.href = `news/${story.id}.html`;
  link.textContent = 'Read more';
  link.setAttribute('aria-label', `Read more about ${story.title}`);
  content.append(label, title, summary, meta, link);
  card.append(imageLink, content);
  return card;
}

